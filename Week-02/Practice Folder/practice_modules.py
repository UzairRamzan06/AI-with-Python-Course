# What are Modules?
# ----------------------------------------------------------
# Modules are pre-written Python files containing useful functions.
# They help us reuse code instead of writing everything from scratch.
# ----------------------------------------------------------

import math

# Example 1: Square root
print("Square root of 25:", math.sqrt(25))

# Example 2: Power function
print("2 raised to power 3:", math.pow(2, 3))

# Example 3: Ceiling and floor
print("Ceiling:", math.ceil(4.2))
print("Floor:", math.floor(4.8))


